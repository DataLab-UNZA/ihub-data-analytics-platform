import Link from 'next/link';
import PageHeader from '@/components/layout/PageHeader';
import Button from '@/components/ui/Button';
import Card, { CardHeader } from '@/components/ui/Card';
import DataTable from '@/components/ui/DataTable';
import { SelectLink } from '@/components/ui/Form';
import Grid from '@/components/ui/Grid';
import LinkList from '@/components/ui/LinkList';
import Pager from '@/components/ui/Pager';
import { readFilters } from '@/lib/filters-server';
import { formatNumber } from '@/lib/format';
import { buildQuery, loadPublications, pageHref, pageWindow, readToolbar, toTableRows } from '@/services/publications';
import { savedSearches } from '@/data/publications';
import { currentUser } from '@/lib/api';
import { can } from '@/lib/permissions';

export const metadata = {
  title: 'Publications',
  description:
    'Explore de-duplicated publications across connected sources, with filters, saved searches and CSV export.',
};

const COLUMNS = [
  { key: 'title', header: 'Title', rowHeader: true, href: (row) => `/publications/${row.key}` },
  { key: 'year', header: 'Year' },
  { key: 'type', header: 'Type' },
  { key: 'oa', header: 'OA' },
  { key: 'sources', header: 'Sources' },
];

const REPOSITORY_OPTIONS = [
  ['', 'Repository: All'],
  ['in', 'Repository: Found'],
];

export default async function PublicationsPage({ searchParams }) {
  const toolbar = readToolbar(await searchParams);
  const filters = await readFilters();
  const [data, user] = await Promise.all([loadPublications(filters, toolbar), currentUser()]);
  const canExport = can(user, 'research:export'); // the API checks this too
  const exportQuery = new URLSearchParams(buildQuery(filters, toolbar)).toString();
  const from = (data.page - 1) * data.page_size + 1;
  const to = from + data.rows.length - 1;

  return (
    <>
      <PageHeader title="Publications" />

      <Card className="mb-24" aria-labelledby="explore-title">
        <CardHeader
          id="explore-title"
          title={`Explore ${formatNumber(data.total)} publications`}
          subtitle="All known publications across connected sources · duplicates merged"
          className="mb-20"
        />
        <form className="toolbar" role="search" action="/publications" method="get" aria-label="Search publications">
          <label className="sr-only" htmlFor="pub-search">
            Search title or DOI
          </label>
          <input
            className="toolbar__search"
            id="pub-search"
            type="search"
            name="q"
            defaultValue={toolbar.q}
            placeholder="Search title or DOI…"
            autoComplete="off"
          />
          <div className="toolbar__filters">
            <SelectLink id="pub-oa" name="oa" label="Open access" options={data.oaOptions} defaultValue={toolbar.oa} />
            <SelectLink
              id="pub-repo"
              name="repository"
              label="Repository"
              options={REPOSITORY_OPTIONS}
              defaultValue={toolbar.repository}
            />
          </div>
          <div className="btn-row btn-row--tight">
            <Button type="submit" variant="secondary" size="sm">
              Search
            </Button>
            {canExport && (
              <Button
                variant="secondary"
                size="sm"
                href={`/export/publications${exportQuery ? `?${exportQuery}` : ''}`}
                prefetch={false}
                download
              >
                CSV
              </Button>
            )}
            <Button variant="secondary" size="sm" aria-disabled="true" title="Excel export is generated by the server">
              Excel
            </Button>
          </div>
        </form>
      </Card>

      <Grid variant="wide-narrow" start>
        <Card aria-labelledby="records-title">
          <CardHeader
            id="records-title"
            title="Publication records"
            subtitle="Select a title to see its authors, sources and how the records were matched"
          />
          {data.rows.length === 0 ? (
            <p className="text-muted">No publications match these filters.</p>
          ) : (
            <DataTable
              id="publication-table"
              caption="Publication records"
              columns={COLUMNS}
              rows={toTableRows(data.rows)}
              variant="roomy"
            />
          )}
          <Pager
            label="Publication records pagination"
            summary={data.total ? `${formatNumber(from)}–${formatNumber(to)} of ${formatNumber(data.total)} records` : '0 records'}
            previous={data.page > 1 ? { label: '← Previous', href: pageHref(toolbar, data.page - 1) } : undefined}
            pages={pageWindow(data.page, data.pages).map((page) =>
              page === '…' ? page : { label: String(page), href: pageHref(toolbar, page), current: page === data.page },
            )}
            next={data.page < data.pages ? { label: 'Next →', href: pageHref(toolbar, data.page + 1) } : undefined}
          />
        </Card>

        <Card aria-labelledby="saved-title">
          <CardHeader id="saved-title" title="Saved searches" subtitle="Private to your account" />
          <LinkList
            divided
            items={savedSearches.map((search) => ({
              label: search.label,
              children: (
                <Link className="saved-search__title" href={search.href}>
                  {search.label}
                  <span className="saved-search__desc">{search.description}</span>
                </Link>
              ),
            }))}
          />
          <Button className="mt-24" variant="secondary" block>
            Save current search
          </Button>
          <p className="text-muted mt-48 text-xs">Exports use the same filters and your role permissions.</p>
        </Card>
      </Grid>
    </>
  );
}
